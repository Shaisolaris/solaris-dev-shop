"""G20 synthetic fixture: help-centre article titles for the demo and the checks. Deterministic; no real data.
Writes fixtures/articles.json and demo/fixture-data.js (the same list, as a script the demo can load from file://)."""
import json
import random
from pathlib import Path

HERE = Path(__file__).resolve().parent
TOPICS = ["billing", "invoices", "refunds", "accounts", "passwords", "two-factor sign-in", "teams", "roles", "exports",
          "imports", "webhooks", "API keys", "rate limits", "backups", "restores", "uploads", "storage", "search",
          "notifications", "email digests", "calendar sync", "time zones", "keyboard shortcuts", "screen readers",
          "high contrast", "audit log", "data retention", "invoices by email", "card payments", "bank transfers"]
VERBS = ["How to set up", "Troubleshooting", "Changing", "Understanding", "Turning off", "Limits for", "FAQ:", "Moving"]


def articles(seed=20, n=240):
    rng = random.Random(seed)
    out, seen = [], set()
    while len(out) < n:
        t = f"{rng.choice(VERBS)} {rng.choice(TOPICS)}"
        if t in seen:
            t = f"{t} ({len(out) + 1})"
        seen.add(t)
        out.append({"id": f"a{len(out) + 1:03d}", "label": t})
    return out


def main():
    rows = articles()
    (HERE / "fixtures").mkdir(exist_ok=True)
    (HERE / "fixtures" / "articles.json").write_text(json.dumps(rows, indent=1) + "\n")
    (HERE / "demo" / "fixture-data.js").write_text(
        "/* Synthetic fixture generated by make_fixtures.py; not real content. */\nwindow.G20_FIXTURE = "
        + json.dumps(rows, separators=(",", ":")) + ";\n")
    print(f"{len(rows)} synthetic articles")


if __name__ == "__main__":
    main()

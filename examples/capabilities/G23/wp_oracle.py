def run(tool, *args, timeout=600):
    p = subprocess.run(shlex.split(tool) + [str(x) for x in args], capture_output=True, text=True, timeout=timeout)
    return p.returncode, p.stdout, p.stderr


class Gen:
    def __init__(self, seed):
        self.r = random.Random(seed)
        self.plugins = sorted({f"{self.r.choice(['zen', 'blue', 'kite', 'nova', 'opal'])}-{self.r.choice(['cart', 'seo', 'forms', 'cache', 'gallery', 'events'])}" for _ in range(12)})[:6]

    def query(self, sql, ms, comp="core", caller="get_option"):
        return {"sql": sql, "ms": round(ms, 3), "caller": caller, "component": comp}

    def request(self, rid, url, total=None, extra=()):
        qs = [self.query(f"SELECT option_value FROM wp_options WHERE option_name = 'opt_{self.r.randint(1, 50)}' LIMIT 1", self.r.uniform(0.1, 0.8)),
              self.query(f"SELECT * FROM wp_posts WHERE ID = {self.r.randint(1, 9999)}", self.r.uniform(0.2, 2.5), caller="WP_Query->get_posts"),
              self.query("SELECT term_id FROM wp_term_relationships WHERE object_id IN (3, 4, 5)", self.r.uniform(0.2, 3.0), caller="wp_get_object_terms")]
        qs += list(extra)
        return {"id": rid, "url": url, "total_ms": round(total if total is not None else self.r.uniform(70, 160), 2),
                "peak_memory_mb": round(self.r.uniform(40, 90), 1), "queries": qs,
                "hooks": [{"hook": "init", "callback": f"{self.plugins[0].replace('-', '_')}_init", "component": f"plugin:{self.plugins[0]}", "ms": round(self.r.uniform(0.5, 6), 2)}]}

    def bundle(self, **kw):
        b = {"schema": "solaris.wp-trace/1", "site": "oracle-site", "environment": "production",
             "source": "synthetic bundle generated by the G23 oracle; not a real site",
             "env": {"php": "8.2.20", "wp": "6.6.1", "host": "oracle-vm"},
             "measurement": {"tool": "oracle loop", "warm_cache": True, "runs_per_url": 6, "concurrency": 1},
             "wp_config": {"WP_DEBUG": False, "WP_DEBUG_DISPLAY": False, "WP_MEMORY_LIMIT": "512M", "WP_CACHE": False,
                           "DB_PASSWORD": SECRET, "AUTH_KEY": SALT, "SAVEQUERIES": False},
             "dropins": [], "active_plugins": [f"{p}/{p}.php" for p in self.plugins], "autoload_bytes": 300000,
             "autoload_top": [{"option": "big_option", "bytes": 90000}], "system_cron": None,
             "requests": [self.request(f"r{i}", self.r.choice(["/", "/blog/", "/cart/"])) for i in range(8)],
             "php_errors": ["[18-Oct-2026 09:00:00 UTC] PHP Notice:  Undefined index: q in /var/www/wp-content/themes/plain/search.php on line 4"],
             "bisect": []}
        b.update(kw)
        return b



    assert "WP_CACHE', true" in B["K4_config_wp_cache_without_dropin"]["wp-config.php"].splitlines()[17 - 1]
    assert 32 * 1024 * 1024 == 33554432
    assert datetime.datetime.fromtimestamp(1792343403, datetime.timezone.utc).isoformat().startswith("2026-10-18T17:10:03")
    assert statistics.median(BEFORE_MISS) == 801 and statistics.median(AFTER_MISS) == 402 and statistics.median(AFTER_HIT) == 39
    assert f"{801 / 402:.2f}" == "1.99" and f"{(801 - 402) / 801 * 100:.1f}" == "49.8"
    assert f"{statistics.mean(BEFORE_MISS) / statistics.mean(AFTER_MISS):.2f}" == "2.01" and f"{(809.4 - 402) / 809.4 * 100:.1f}" == "50.3"
    stats_total = sum(float(e[2]) for e in SLOW_STATS)
    assert len(SLOW_STATS) == 9 and abs(stats_total - 2.793978) < 1e-6 and stats_total < 3.912345  # acme wins on max and on total
    assert "line 40" in FATAL_REDECLARE and "shop-extras/functions.php" in FATAL_REDECLARE
    assert "advanced-cache.php" not in B["K4_config_wp_cache_without_dropin"] and "wp-content/advanced-cache.php" not in B["K4_config_wp_cache_without_dropin"]
    q = json.loads(B["K5_slow_query_theme_qm"]["qm-db.json"])["queries"]
    assert max(q, key=lambda x: x["time"])["component"] == "Theme: solaris-child" and sum(x["time"] for x in q[1:]) < 2.480113

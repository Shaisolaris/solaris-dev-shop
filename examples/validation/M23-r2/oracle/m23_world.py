def write(root):
    for name, files in bundles().items():
        for rel, txt in files.items():
            p = os.path.join(root, name, rel)
            os.makedirs(os.path.dirname(p), exist_ok=True)
            with open(p, "w", encoding="utf-8") as f:
                f.write(txt)


